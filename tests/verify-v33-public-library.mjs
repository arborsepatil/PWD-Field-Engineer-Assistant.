import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const dir=path.resolve(import.meta.dirname,'..');
const read=x=>fs.readFileSync(path.join(dir,x),'utf8');
const source=read('library-public-catalog.js'),old=read('library-drive-catalog.js');
const html=read('library.html'),viewer=read('pdf_viewer.html'),sw=read('sw.js');
const context={window:{}};
vm.runInNewContext(source,context);
const records=Array.from(context.window.PWDPublicBookCatalogue);
assert.equal(records.length,12);
assert.match(old,/window\.PWDDrivePDFCatalog=\[\];/);
assert.ok(!html.includes('library-drive-catalog.js')&&!html.includes('library-offline.js'));
assert.ok(!html.includes('Save multiple PDFs')&&!html.includes('Export copy'));
assert.ok(!html.includes('drive.google.com/file/d/'));
assert.ok(!viewer.includes('drive.google.com/file/d/'));
assert.ok(viewer.includes('#driveBtn,#fallbackBtn{display:none!important}'));
assert.ok(html.includes('View on publisher ↗'));
assert.ok(html.includes("anchor.target='_blank'"));
assert.ok(html.includes('Internet may be required'));
assert.ok(html.includes('does not mean copyright-free'));
assert.ok(sw.includes("'./library-public-catalog.js'"));
const allowed=new Set(['pwd.maharashtra.gov.in','cpwd.gov.in','www.bis.gov.in','irc.nic.in','gr.maharashtra.gov.in']);
const links=new Set(),groups=new Set();
for(const item of records){
 assert.ok(item.title&&item.publisher&&item.note);
 assert.ok(!('id' in item)&&!('viewer' in item));
 const u=new URL(item.url);
 assert.equal(u.protocol,'https:');
 assert.ok(allowed.has(u.hostname),'Source must be publisher');
 assert.ok(!links.has(item.url),'Duplicate URL');
 links.add(item.url);groups.add(item.section);
 assert.ok(['book','index','portal','catalogue'].includes(item.kind));
}
for(const cat of ['rules','ssr','spec','code','gr'])assert.ok(groups.has(cat));
const inline=html.match(/<script>([\s\S]*?)<\/script>/);assert.ok(inline);
new vm.Script(inline[1]);
const pack=read('android/scripts/prepare_assets.py');
assert.ok(pack.includes('library-public-catalog.js'));
console.log('V33 public-only library PASS: 12 verified official references; no private Drive IDs in shared catalogue or viewer; five filters and safe view controls.');
